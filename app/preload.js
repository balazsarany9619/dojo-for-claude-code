const { contextBridge, ipcRenderer, webUtils, webFrame } = require('electron');

contextBridge.exposeInMainWorld('cockpit', {
  platform: process.platform,
  listProjects: () => ipcRenderer.invoke('projects:list'),
  loadCategories: () => ipcRenderer.invoke('categories:load'),
  hasHistory: (dir) => ipcRenderer.invoke('history:has', dir),
  detectConversation: (dir, since, exclude) => ipcRenderer.invoke('claude:detect', { dir, since, exclude }),
  createPty: (opts) => ipcRenderer.invoke('pty:create', opts),
  write: (id, data) => ipcRenderer.send('pty:write', { id, data }),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', { id, cols, rows }),
  kill: (id) => ipcRenderer.send('pty:kill', { id }),
  onData: (cb) => ipcRenderer.on('pty:data', (_e, m) => cb(m)),
  onExit: (cb) => ipcRenderer.on('pty:exit', (_e, m) => cb(m)),
  onFocus: (cb) => ipcRenderer.on('win:focus', (_e, f) => cb(f)),
  onSelectAll: (cb) => ipcRenderer.on('edit:selectAll', () => cb()),
  onHook: (cb) => ipcRenderer.on('hook:event', (_e, m) => cb(m)),
  notify: (title, body, silent) => ipcRenderer.send('notify', { title, body, silent }),
  loadSettings: () => ipcRenderer.invoke('settings:load'),
  saveSettings: (v) => ipcRenderer.send('settings:save', v),
  onOpenSettings: (cb) => ipcRenderer.on('settings:open', () => cb()),
  setZoom: (f) => webFrame.setZoomFactor(f),
  zoom: () => webFrame.getZoomFactor(),
  clipRead: () => ipcRenderer.invoke('clip:read'),
  clipWrite: (t) => ipcRenderer.send('clip:write', t),
  clipWriteRich: (text, html) => ipcRenderer.send('clip:writeRich', { text, html }),
  drafts: (dir, cid) => ipcRenderer.invoke('transcript:drafts', { dir, cid }),
  openFolder: (p) => ipcRenderer.send('open:folder', p),
  openExternal: (url) => ipcRenderer.send('open:external', url),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file) || ''; } catch { return ''; } },
  loadState: () => ipcRenderer.invoke('state:load'),
  saveState: (s) => ipcRenderer.send('state:save', s),
  fsList: (dir) => ipcRenderer.invoke('fs:list', dir),
  fsSearch: (root, query) => ipcRenderer.invoke('fs:search', { root, query }),
  fsCreate: (dir, name, folder) => ipcRenderer.invoke('fs:create', { dir, name, folder }),
  fsOpen: (p) => ipcRenderer.send('fs:open', p),
  fsReveal: (p) => ipcRenderer.send('fs:reveal', p),
  stats: (days) => ipcRenderer.invoke('stats:get', days),
  context: (dir, cid) => ipcRenderer.invoke('context:get', { dir, cid }),
  radar: () => ipcRenderer.invoke('radar:get'),
  handoffMtime: (dir) => ipcRenderer.invoke('handoff:mtime', dir),
  gitPush: (dir) => ipcRenderer.invoke('git:push', dir),
  codeStats: (days) => ipcRenderer.invoke('code:get', days),
  firstPrompt: (dir, cid) => ipcRenderer.invoke('prompt:first', { dir, cid }),
  brainFiles: (dir) => ipcRenderer.invoke('brain:files', dir),
  brainRead: (dir, rel) => ipcRenderer.invoke('brain:read', { dir, rel }),
  brainDiff: (dir, rel) => ipcRenderer.invoke('brain:diff', { dir, rel }),
  createProject: (name, template) => ipcRenderer.invoke('project:create', { name, template }),
  captureCard: (rect, save) => ipcRenderer.invoke('card:capture', { rect, save }),
});
